"""The asset provenance log.

Every asset records how it was made — drawn in code, generated by a
model, or taken from a licensed library. Stores ask about AI content,
and the disclosure draft below is built from these records. An asset
with no record is not used; the factory can list such assets as
unrecorded.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from pathlib import Path

SOURCES = ("code", "ai", "library")
_AI_SOURCES = {"ai", "ai-generated", "aigenerated"}
_CODE_SOURCES = {"code", "code-drawn", "codedrawn"}
_LIBRARY_SOURCES = {"library", "licensed", "licensed library"}


class ProvenanceError(Exception):
    """Raised for bad provenance records or unreadable log files."""


def provenance_path_for(project_dir) -> Path:
    """The provenance file for a project directory (or the file itself)."""
    path = Path(project_dir)
    if path.is_file():
        return path
    return path / ".weaverbird" / "provenance.json"


def _load(project_dir) -> dict:
    path = provenance_path_for(project_dir)
    if not path.exists():
        return {"records": []}
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise ProvenanceError(f"Provenance file is not valid JSON: {path}") from exc
    if not isinstance(data, dict) or not isinstance(data.get("records"), list):
        return {"records": []}
    return data


def _save(project_dir, data: dict) -> None:
    path = provenance_path_for(project_dir)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def add_record(project_dir, asset: str, source: str, note: str = "",
               provider: str | None = None) -> dict:
    """Record how one asset was made."""
    if source not in SOURCES:
        raise ProvenanceError(
            f"Source must be one of {', '.join(SOURCES)}, got {source!r}."
        )
    if not asset:
        raise ProvenanceError("An asset path is required.")
    record = {
        "asset": str(asset),
        "source": source,
        "provider": provider or "",
        "note": note or "",
        "recorded_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    data = _load(project_dir)
    data["records"] = [r for r in data["records"] if r.get("asset") != record["asset"]]
    data["records"].append(record)
    _save(project_dir, data)
    return record


def list_records(project_dir) -> list[dict]:
    """All provenance records in a project."""
    return list(_load(project_dir)["records"])


def recorded_assets(project_dir) -> set[str]:
    return {str(r.get("asset")) for r in list_records(project_dir)}


def unrecorded_assets(project_dir, asset_paths) -> list[str]:
    """Assets from the given list that have no provenance record."""
    recorded = recorded_assets(project_dir)
    return [str(a) for a in asset_paths if str(a) not in recorded]


def _kind(source: str) -> str:
    lowered = str(source).strip().lower()
    if lowered in _AI_SOURCES:
        return "ai"
    if lowered in _LIBRARY_SOURCES:
        return "library"
    return "code"


def disclosure_text(project_dir) -> str:
    """A plain-text AI-content disclosure draft for a store content survey.

    Built only from the provenance records — what is not recorded is
    called out as such, never guessed.
    """
    records = list_records(project_dir)
    ai = [r for r in records if _kind(r.get("source", "")) == "ai"]
    library = [r for r in records if _kind(r.get("source", "")) == "library"]
    code = [r for r in records if _kind(r.get("source", "")) == "code"]

    lines = ["AI content disclosure (draft — check before submitting)", ""]
    if ai:
        lines.append("This game contains content generated with AI tools:")
        for record in ai:
            detail = str(record.get("asset"))
            provider = str(record.get("provider", "")).strip()
            if provider:
                detail += f" — generated with {provider}"
            note = str(record.get("note", "")).strip()
            if note:
                detail += f" ({note})"
            lines.append(f"- {detail}")
    else:
        lines.append("No AI-generated assets are recorded for this game.")
    lines.append("")
    if library:
        lines.append("Licensed third-party assets:")
        for record in library:
            detail = str(record.get("asset"))
            note = str(record.get("note", "")).strip()
            if note:
                detail += f" — {note}"
            lines.append(f"- {detail}")
        lines.append("")
    if code:
        lines.append("Assets created in code, without AI generation:")
        for record in code:
            lines.append(f"- {record.get('asset')}")
        lines.append("")
    lines.append(
        f"Provenance records held: {len(records)} "
        f"({len(ai)} AI-generated, {len(library)} licensed, {len(code)} code-created)."
    )
    return "\n".join(lines) + "\n"
